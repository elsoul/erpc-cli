#[cfg(unix)]
#[test]
fn controller_and_cli_have_identical_network_and_source_pins() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let output = std::process::Command::new("python3")
        .args([
            "-c",
            "import json,runpy,sys; print(json.dumps(runpy.run_path(sys.argv[1])['PINS']))",
        ])
        .arg(root.join("templates/node/control.py"))
        .env("PYTHONDONTWRITEBYTECODE", "1")
        .output()
        .expect("read carried public catalog");
    assert!(output.status.success());
    let pins: serde_json::Value = serde_json::from_slice(&output.stdout).expect("public pins");
    for name in ["mainnet", "testnet"] {
        let network = erpc_chain_near::network::get(name).expect("network");
        assert_eq!(pins[name]["version"], network.version);
        assert_eq!(pins[name]["commit"], network.commit);
        assert_eq!(pins[name]["image"], network.image);
        assert_eq!(pins[name]["genesis_hash"], network.genesis_hash);
        assert_eq!(pins[name]["genesis_height"], network.genesis_height);
        assert_eq!(pins[name]["genesis_sha256"], network.genesis_sha256);
        assert_eq!(pins[name]["config_sha256"], network.config_sha256);
    }
}

#[test]
fn embedded_templates_do_not_include_local_python_bytecode() {
    fn inspect(directory: &include_dir::Dir<'_>) {
        for file in directory.files() {
            let name = file.path().to_string_lossy();
            assert!(
                !name.contains("__pycache__") && !name.ends_with(".pyc") && !name.ends_with(".pyo"),
                "local generated bytecode in runtime resources: {name}"
            );
        }
        for child in directory.dirs() {
            inspect(child);
        }
    }
    inspect(&erpc_chain_near::TEMPLATES);
}

