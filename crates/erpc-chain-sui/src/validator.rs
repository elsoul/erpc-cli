//! Validator metadata and an external-signing boundary. Owner keys are never imported.
use base64::{Engine as _, engine::general_purpose::STANDARD};
use erpc_auth::store::one_password::OpRunner;
use secrecy::SecretString;
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use zeroize::Zeroize as _;

/// JSON form of the official `GenesisValidatorInfo`. JSON is also accepted by its YAML reader.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Metadata {
    /// Public on-chain validator identity and network addresses.
    pub info: Info,
    /// BLS proof generated by the official operator tool, never an owner signature.
    pub proof_of_possession: String,
}
/// Official validator metadata uses kebab-case field names.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case", deny_unknown_fields)]
pub struct Info {
    /// Public display name.
    pub name: String,
    /// Owner address. The matching owner key stays with the operator.
    pub account_address: String,
    /// BLS public key, base64 (min-signature mode).
    pub protocol_key: String,
    /// Consensus worker public key, base64.
    pub worker_key: String,
    /// Peer identity public key, base64.
    pub network_key: String,
    /// Gas price in MIST.
    pub gas_price: u64,
    /// Commission in basis points.
    pub commission_rate: u64,
    /// Validator transaction interface multiaddress.
    pub network_address: String,
    /// State-sync multiaddress.
    pub p2p_address: String,
    /// Historical field name for the consensus listener.
    pub narwhal_primary_address: String,
    /// Historical worker address in the official metadata format.
    pub narwhal_worker_address: String,
    /// Display description.
    pub description: String,
    /// Public image location; never fetched by this module.
    pub image_url: String,
    /// Public project location; never fetched by this module.
    pub project_url: String,
}

/// Check a 1Password field reference before passing it as an argument.
/// # Errors
/// Refuses anything other than three nonempty, plain path components.
pub fn reference(value: &str) -> Result<(), String> {
    let parts = value
        .strip_prefix("op://")
        .ok_or("use a 1Password field reference")?
        .split('/')
        .collect::<Vec<_>>();
    if parts.len() != 3
        || parts.iter().any(|p| {
            p.is_empty()
                || !p
                    .bytes()
                    .all(|c| c.is_ascii_alphanumeric() || matches!(c, b'-' | b'_'))
        })
    {
        return Err(
            "the key reference must contain vault/item/field using IDs and simple field names"
                .to_owned(),
        );
    }
    Ok(())
}

/// Read key material directly into a secret buffer without propagating provider output in errors.
/// # Errors
/// Refuses malformed references, failed reads and oversized responses.
pub fn read_key(runner: &impl OpRunner, field: &str) -> Result<SecretString, String> {
    reference(field)?;
    let mut result = runner
        .run(&["read", "--no-newline", field], None)
        .map_err(|_| "could not read the Sui key from 1Password")?;
    result.stderr.zeroize();
    if !result.success || result.stdout.len() > 512 {
        result.stdout.zeroize();
        return Err("1Password did not return a bounded Sui key".to_owned());
    }
    Ok(SecretString::from(result.stdout))
}

impl Metadata {
    /// Parse and structurally validate public metadata only.
    /// # Errors
    /// Refuses unknown fields, invalid keys/addresses, dangerous strings or unsupported port choices.
    /// Cryptographic `PoP` and live admission are verified by external transaction simulation.
    pub fn parse(text: &str) -> Result<Self, String> {
        if text.len() > 32_768 {
            return Err("validator metadata exceeds 32 KiB".to_owned());
        }
        let metadata: Self = serde_json::from_str(text).map_err(
            |_| "expected public GenesisValidatorInfo as JSON; do not include private keys",
        )?;
        metadata.validate()?;
        Ok(metadata)
    }
    /// Validate a stored public record every time it crosses into a host configuration.
    /// # Errors
    /// Returns a diagnostic that never includes private input values.
    pub fn validate(&self) -> Result<(), String> {
        let info = &self.info;
        for (key, len) in [
            (&info.protocol_key, 96),
            (&info.network_key, 32),
            (&info.worker_key, 32),
            (&self.proof_of_possession, 48),
        ] {
            if STANDARD.decode(key).map(|b| b.len()) != Ok(len) {
                return Err("invalid validator public key or proof encoding".to_owned());
            }
        }
        let address = info
            .account_address
            .strip_prefix("0x")
            .ok_or("owner address needs 0x prefix")?;
        if address.len() != 64 || !address.bytes().all(|b| b.is_ascii_hexdigit()) {
            return Err("owner address must be 32 bytes".to_owned());
        }
        if info.commission_rate > 10_000 || info.gas_price == 0 {
            return Err("invalid gas price or commission".to_owned());
        }
        for value in [
            &info.name,
            &info.description,
            &info.image_url,
            &info.project_url,
        ] {
            if value.len() > 256 || !value.is_ascii() || value.chars().any(char::is_control) {
                return Err("validator display metadata must be printable ASCII, at most 256 bytes per field".to_owned());
            }
        }
        let host = multiaddr(&info.network_address, "tcp/8080/http")?;
        for (value, suffix) in [
            (&info.p2p_address, "udp/8084"),
            (&info.narwhal_primary_address, "udp/8081"),
            (&info.narwhal_worker_address, "udp/8082"),
        ] {
            if multiaddr(value, suffix)? != host {
                return Err(
                    "validator interfaces must advertise the same dedicated host".to_owned(),
                );
            }
        }
        Ok(())
    }
    /// External commands use the operator's wallet. They serialize or simulate, never broadcast.
    #[must_use]
    pub fn preparation(&self, network: &str) -> Value {
        json!({
            "owner":self.info.account_address,"network":network,"validator_info":self,
            "candidate_unsigned":["sui","validator","--client.env",network,"become-candidate","validator.info","--serialize-unsigned-transaction"],
            "join_unsigned":["sui","validator","--client.env",network,"join-committee","--serialize-unsigned-transaction"],
            "dry_run_unsigned":["sui","client","--client.env",network,"serialized-tx","<TX_BYTES>","--dry-run"],
            "validation":"Use the correct-network operator wallet to build and dry-run unsigned bytes before external signing/broadcast. An unsigned candidate transaction must succeed before funding its pool and preparing join.",
            "admission":"Pinned framework uses phased voting-power admission (12, then 6, then 3 at 14-epoch intervals from on-chain VotingPowerAdmissionStartEpochKey); no fixed 30M SUI requirement is assumed. Current phase and sufficient stake require live dry-run.",
            "proof_verification":"Metadata shape only here; proof-of-possession and current admission require successful official transaction simulation."
        })
    }
}
fn multiaddr<'a>(value: &'a str, suffix: &str) -> Result<&'a str, String> {
    let rest = value
        .strip_prefix("/dns/")
        .ok_or("validator metadata must use a public DNS multiaddress")?;
    let (host, path) = rest
        .split_once('/')
        .ok_or("invalid validator multiaddress")?;
    if path != suffix
        || host.is_empty()
        || host.len() > 253
        || !host.contains('.')
        || host.starts_with(['-', '.'])
        || host.ends_with(['-', '.'])
        || !host
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'-' | b'.'))
    {
        return Err(
            "validator metadata has an invalid host or unsupported listener port".to_owned(),
        );
    }
    Ok(host)
}

#[cfg(test)]
mod tests {
    use super::*;
    use erpc_auth::store::{StoreError, one_password::OpOutput};
    use secrecy::ExposeSecret as _;

    fn fixture() -> Value {
        json!({"info":{
            "name":"Operator", "account-address":format!("0x{}", "0".repeat(64)),
            "protocol-key":STANDARD.encode([0;96]), "worker-key":STANDARD.encode([0;32]),
            "network-key":STANDARD.encode([1;32]), "gas-price":1000,"commission-rate":1000,
            "network-address":"/dns/validator.example.org/tcp/8080/http",
            "p2p-address":"/dns/validator.example.org/udp/8084",
            "narwhal-primary-address":"/dns/validator.example.org/udp/8081",
            "narwhal-worker-address":"/dns/validator.example.org/udp/8082",
            "description":"", "image-url":"", "project-url":""
        },"proof_of_possession":STANDARD.encode([0;48])})
    }
    #[test]
    fn metadata_rejects_secret_fields_wrong_keys_and_network_addresses() {
        let original = fixture();
        let parsed = Metadata::parse(&original.to_string()).expect("public fixture");
        let command = parsed.preparation("testnet");
        assert_eq!(command["candidate_unsigned"][2], "--client.env");
        assert_eq!(
            command["candidate_unsigned"][6],
            "--serialize-unsigned-transaction"
        );
        for (field, value) in [
            ("worker-key", json!(STANDARD.encode([0; 33]))),
            ("commission-rate", json!(10001)),
            (
                "network-address",
                json!("/dns/validator.example.org/tcp/22/http"),
            ),
            ("p2p-address", json!("/dns/another.example.org/udp/8084")),
            ("name", json!("injected\nvalue")),
            ("owner-key", json!("refused")),
        ] {
            let mut changed = original.clone();
            changed["info"][field] = value;
            assert!(Metadata::parse(&changed.to_string()).is_err(), "{field}");
        }
    }
    struct Provider(bool);
    impl OpRunner for Provider {
        fn run(&self, args: &[&str], stdin: Option<&str>) -> Result<OpOutput, StoreError> {
            assert_eq!(args, ["read", "--no-newline", "op://vault/item/field"]);
            assert!(stdin.is_none());
            Ok(OpOutput {
                success: self.0,
                stdout: "private fixture".to_owned(),
                stderr: "private fixture".to_owned(),
            })
        }
    }
    #[test]
    fn private_provider_output_is_bounded_and_never_returned_in_errors() {
        assert_eq!(
            read_key(&Provider(true), "op://vault/item/field")
                .expect("read")
                .expose_secret(),
            "private fixture"
        );
        let error = read_key(&Provider(false), "op://vault/item/field").expect_err("failure");
        assert!(!error.contains("private fixture"));
        for value in [
            "op://vault/item/field/extra",
            "op://vault/item/field --reveal",
            "not-an-op-reference",
            "op:///item/field",
        ] {
            assert!(reference(value).is_err());
        }
    }
}
